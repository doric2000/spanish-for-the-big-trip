-- Stage05: the attempt log behind POST /v1/units/:unitId/attempts.
-- Design: ../../content/storage-model.json (activity_attempts, access.progress)
-- and docs/planning/approved-decisions.json#stage05_activity_attempts.
-- One row per learner action. The (user_id, request_id) key makes a retried
-- request idempotent: the server returns the stored result instead of advancing
-- twice. Learners have no direct access; only the trusted server reads and
-- inserts, and rows are never updated.
create table public.activity_attempts (
  -- Deleting the account (App Store guideline 5.1.1(v)) deletes its attempts.
  user_id uuid not null references auth.users (id) on delete cascade,
  -- Generated by the app and reused unchanged when the same request is retried.
  request_id uuid not null,
  unit_id text not null,
  revision integer not null,
  activity_id text not null,
  -- SHA-256 of the canonical request (content/src/digest.ts). Same request_id
  -- with a different fingerprint is a conflict, not a retry.
  request_fingerprint text not null,
  -- What the learner sent, e.g. {"kind": "choice", "choiceId": "hello"}.
  response jsonb not null,
  -- What the server answered (outcome, feedback, progress); replayed on retry.
  server_result jsonb not null,
  created_at timestamptz not null default now(),
  primary key (user_id, request_id),
  -- An attempt belongs to an exact revision, so that revision can never be removed.
  constraint activity_attempts_revision_fkey foreign key (unit_id, revision)
    references public.unit_revisions (unit_id, revision) on delete restrict,
  constraint activity_attempts_ids_not_blank check (
    length(btrim(unit_id)) > 0 and length(btrim(activity_id)) > 0
  ),
  constraint activity_attempts_fingerprint_sha256
    check (request_fingerprint ~ '^[a-f0-9]{64}$'),
  constraint activity_attempts_response_is_object
    check (jsonb_typeof(response) = 'object'),
  constraint activity_attempts_result_is_object
    check (jsonb_typeof(server_result) = 'object')
);

-- Supports the foreign key check when a revision row is touched.
-- The primary key already starts with user_id for per-learner lookups.
create index activity_attempts_revision_idx
  on public.activity_attempts (unit_id, revision);

-- RLS on with no learner policy: learners cannot read or write attempts
-- (Dor, 2026-10-19). The server role bypasses RLS and must check ownership itself.
alter table public.activity_attempts enable row level security;

revoke all privileges on table public.activity_attempts
  from public, anon, authenticated;
-- An append-only log: no UPDATE or DELETE, even for the server. Rows go only
-- with their account (cascade above).
grant select, insert on table public.activity_attempts to service_role;

comment on table public.activity_attempts is
  'Append-only attempt log keyed by (user_id, request_id) for idempotent submissions. Server-only; kept until the account is deleted. Never store tokens or audio here.';
comment on column public.activity_attempts.request_fingerprint is
  'SHA-256 of the canonical request including the path unitId. A reused request_id with another fingerprint is rejected as a conflict.';
