import type { ChapterPlan } from './chapter-release.js';
import type { Unit } from './schema.js';

// SQL string literal. With standard_conforming_strings (the PostgreSQL default)
// only the single quote needs escaping.
export function sqlText(value: string): string {
  if (value.includes('\0')) throw new Error('NUL characters cannot be stored as SQL text');
  return `'${value.replaceAll("'", "''")}'`;
}

// Builds an idempotent SQL script that stores one validated DRAFT revision.
// Drafts are never learner-readable; publication stays with the whole-chapter
// release check. Running the script twice is safe. If the revision was already
// published with different content, the script stops instead of changing it.
export function buildDraftSeedSql(plan: ChapterPlan, unit: Unit, digest: string, sourcePath: string): string {
  if (unit.status !== 'draft') throw new Error('Only draft revisions are seeded; publishing uses the chapter release check');
  if (!/^[a-f0-9]{64}$/.test(digest)) throw new Error('Expected a SHA-256 source digest');
  const chapterIndex = plan.chapters.findIndex(c => c.id === unit.chapterId);
  const chapter = plan.chapters[chapterIndex];
  if (!chapter) throw new Error(`${unit.chapterId} is not in the release plan`);
  const unitPosition = chapter.unitIds.indexOf(unit.id) + 1;
  if (unitPosition === 0) throw new Error(`${unit.id} is not planned in ${chapter.id}`);

  const aliases = `array[${unit.aliases.map(sqlText).join(', ')}]::text[]`;
  const payload = sqlText(JSON.stringify(unit));
  return `-- GENERATED by content/src/seed-sql.ts from ${sourcePath}. Do not edit; regenerate with:
--   npm.cmd --prefix content run seed:sql
-- Stores ${unit.id} revision ${unit.revision} as a DRAFT (not learner-readable).
-- Source digest: ${digest}
begin;

insert into public.courses (id, title_he)
values (${sqlText(plan.course.id)}, ${sqlText(plan.course.titleHe)})
on conflict (id) do update set title_he = excluded.title_he;

insert into public.chapters (id, course_id, title_he, position)
values (${sqlText(chapter.id)}, ${sqlText(plan.course.id)}, ${sqlText(chapter.titleHe)}, ${chapterIndex + 1})
on conflict (id) do update set title_he = excluded.title_he, position = excluded.position;

insert into public.units (id, chapter_id, aliases, title_he, position)
values (${sqlText(unit.id)}, ${sqlText(chapter.id)}, ${aliases}, ${sqlText(unit.titleHe)}, ${unitPosition})
on conflict (id) do update
  set aliases = excluded.aliases, title_he = excluded.title_he, position = excluded.position;

-- A published revision is never overwritten: the WHERE skips it and the check below stops.
insert into public.unit_revisions
  (unit_id, revision, schema_version, authoring_payload, source_digest, status)
values (${sqlText(unit.id)}, ${unit.revision}, ${unit.schemaVersion}, ${payload}::jsonb, ${sqlText(digest)}, 'draft')
on conflict (unit_id, revision) do update
  set schema_version = excluded.schema_version,
    authoring_payload = excluded.authoring_payload,
    source_digest = excluded.source_digest
  where public.unit_revisions.status = 'draft';

do $seed$
begin
  if not exists (
    select 1 from public.unit_revisions
    where unit_id = ${sqlText(unit.id)} and revision = ${unit.revision}
      and source_digest = ${sqlText(digest)}
  ) then
    raise exception '${unit.id} revision ${unit.revision} is published with different content; create a new revision instead';
  end if;
end;
$seed$;

commit;

select unit_id, revision, status,
  jsonb_array_length(authoring_payload -> 'activities') as activities,
  source_digest = ${sqlText(digest)} as digest_matches
from public.unit_revisions
where unit_id = ${sqlText(unit.id)};
`;
}
